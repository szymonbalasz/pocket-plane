// FR-SHELL-114 (sprint 8, WF1): the session-replay harness's cells. Loads `session-sim-11`
// in-process, builds the three states by DM commands (`ambush` as loaded, `ambush-revealed` after
// Reveal all, `escort` after End → Start "Escort to the Ford") and, per state and viewer (DM,
// player-1, player-2), extracts the scene and the tokens that viewer draws. The committed
// `replay-cells.generated.ts` must match (`UPDATE_CELLS=1` rewrites it); the client-side harness
// (FR-SHELL-115) imports that data file only.
import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { closeDb, type Db, openFileDb } from "@server/db/client";
import { encounter, entity, player } from "@server/db/schema";
import {
  startTestServer,
  TEST_SECRET,
  type TestClient,
  type TestServer,
} from "@server/testing/harness";
import { leakScan } from "@server/ws/testing/convergence";
import { FOG_INTENTS } from "@shared/fog-of-war/schemas";
import {
  SCENE_TYPE,
  TOKEN_TYPE,
  type TokenRecord,
  type TokenSize,
} from "@shared/scenes-map/schemas";
import { eq } from "drizzle-orm";
import { loadBundle } from "../../index";

const GENERATED = fileURLToPath(
  new URL(
    "../../../src/client/common/features/play-shell/replay-cells.generated.ts",
    import.meta.url,
  ),
);

const DM = { role: "dm" as const, secret: TEST_SECRET };

// The generated module's types (fixtures may not import the client, AGENTS §9.1: the test
// compares the text it would write).
type ReplayState = "ambush" | "ambush-revealed" | "escort";
type ReplayViewer = "dm" | "player-1" | "player-2";
interface CellScene {
  mapWidth: number;
  mapHeight: number;
  gridCellSize: number;
  gridOffsetX: number;
  gridOffsetY: number;
}
interface CellToken {
  id: string;
  name: string;
  col: number;
  row: number;
  size: TokenSize;
  pc: boolean;
  owned: boolean;
  hidden: boolean;
}
type ReplayCells = Record<
  ReplayState,
  Record<ReplayViewer, { scene: CellScene; tokens: readonly CellToken[] }>
>;

const barrier = async (c: TestClient) => {
  c.send({ type: "ping" });
  await c.next("pong");
};

async function ack(c: TestClient, name: string, payload: unknown): Promise<unknown> {
  const id = c.intent(name, payload);
  for (;;) {
    const f = await c.next(undefined, 5000);
    if ((f.type === "ack" || f.type === "reject") && f.intentId === id) {
      if (f.type === "reject") throw new Error(`${name} rejected: ${JSON.stringify(f)}`);
      return f.result;
    }
  }
}

/** The active scene and the tokens on it, as this client holds (and so draws) them. */
function cellsOf(c: TestClient, sceneId: string): { scene: CellScene; tokens: CellToken[] } {
  const s = c.store.records[SCENE_TYPE]?.[sceneId] as
    | {
        mapWidth: number;
        mapHeight: number;
        gridCellSize: number;
        gridOffsetX: number;
        gridOffsetY: number;
      }
    | undefined;
  if (!s) throw new Error(`scene ${sceneId} not in the store`);
  const tokens = (Object.values(c.store.records[TOKEN_TYPE] ?? {}) as TokenRecord[])
    .filter((t) => t.sceneId === sceneId)
    .sort((a, b) => a.seq - b.seq || a.id.localeCompare(b.id))
    .map(
      (t): CellToken => ({
        id: t.id,
        name: t.name,
        col: t.col,
        row: t.row,
        size: t.size,
        // #318: a player character (a character with an owner); pets and summons are not.
        pc: t.characterId !== null && t.ownerPlayerId !== null,
        owned: t.ownerPlayerId !== null,
        hidden: t.hidden,
      }),
    );
  return {
    scene: {
      mapWidth: s.mapWidth,
      mapHeight: s.mapHeight,
      gridCellSize: s.gridCellSize,
      gridOffsetX: s.gridOffsetX,
      gridOffsetY: s.gridOffsetY,
    },
    tokens,
  };
}

/** The generated module's text (Biome-formatted shape: one token per line). */
function render(cells: ReplayCells): string {
  const tok = (t: CellToken) =>
    `      { id: ${JSON.stringify(t.id)}, name: ${JSON.stringify(t.name)}, col: ${t.col}, row: ${t.row}, size: ${JSON.stringify(t.size)}, pc: ${t.pc}, owned: ${t.owned}, hidden: ${t.hidden} },`;
  const lines: string[] = [
    "// Generated by fixtures/units/play-shell/replay-cells.test.ts (FR-SHELL-114); do not edit.",
    "// `UPDATE_CELLS=1 bun test fixtures/units/play-shell/replay-cells.test.ts` rewrites it.",
    "// Test-only data: `session-sim-11` states per viewer, read by the session-replay harness.",
    'import type { TokenSize } from "@shared/scenes-map/schemas";',
    "",
    'export type ReplayState = "ambush" | "ambush-revealed" | "escort";',
    'export type ReplayViewer = "dm" | "player-1" | "player-2";',
    "",
    "export interface CellScene {",
    "  mapWidth: number;",
    "  mapHeight: number;",
    "  gridCellSize: number;",
    "  gridOffsetX: number;",
    "  gridOffsetY: number;",
    "}",
    "",
    "/** A drawn token: `pc` = a player character (#318), `hidden` = the DM's hidden flag. */",
    "export interface CellToken {",
    "  id: string;",
    "  name: string;",
    "  col: number;",
    "  row: number;",
    "  size: TokenSize;",
    "  pc: boolean;",
    "  owned: boolean;",
    "  hidden: boolean;",
    "}",
    "",
    "export type ReplayCells = Record<",
    "  ReplayState,",
    "  Record<ReplayViewer, { scene: CellScene; tokens: readonly CellToken[] }>",
    ">;",
    "",
    "// biome-ignore format: one token per line keeps the diff of a fixture change readable",
    "export const REPLAY_CELLS: ReplayCells = {",
  ];
  for (const [state, viewers] of Object.entries(cells)) {
    lines.push(`  ${JSON.stringify(state)}: {`);
    for (const [viewer, v] of Object.entries(viewers)) {
      const sc = v.scene;
      lines.push(`    ${JSON.stringify(viewer)}: {`);
      lines.push(
        `      scene: { mapWidth: ${sc.mapWidth}, mapHeight: ${sc.mapHeight}, gridCellSize: ${sc.gridCellSize}, gridOffsetX: ${sc.gridOffsetX}, gridOffsetY: ${sc.gridOffsetY} },`,
      );
      lines.push("      tokens: [");
      for (const t of v.tokens) lines.push(`  ${tok(t)}`);
      lines.push("      ],");
      lines.push("    },");
    }
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

describe("FR-SHELL-114 session-replay cells (session-sim-11)", () => {
  let h: TestServer;
  let db: Db;
  let dir: string;
  let links: Record<string, string>;

  beforeAll(async () => {
    const loaded = await loadBundle("session-sim-11", { dmSecret: TEST_SECRET, testMode: true });
    dir = loaded.dir;
    db = openFileDb(loaded.config.dbPath);
    links = Object.fromEntries(
      db
        .select()
        .from(player)
        .all()
        .map((r) => [r.name, r.linkToken]),
    );
    h = await startTestServer({ db, fake: false });
  });

  afterAll(async () => {
    await h.stop();
    closeDb(db);
    try {
      rmSync(dir, { recursive: true, force: true });
    } catch {
      // Windows may hold the WAL briefly; a leftover temp dir is harmless.
    }
  });

  test("FR-SHELL-114 cells are current (ambush, ambush-revealed, escort × DM, player-1, player-2)", async () => {
    const ambush = db.select().from(encounter).where(eq(encounter.status, "started")).get();
    if (!ambush) throw new Error("session-sim-11: no started encounter");
    const sceneId = ambush.sceneId as string;
    const dmActor = { role: "dm" as const, playerId: null, campaignId: ambush.campaignId };
    h.s.commands.run("map.activateScene", { sceneId }, { actor: dmActor });
    const viewers: Record<ReplayViewer, TestClient> = {
      dm: await h.live(DM),
      "player-1": await h.live({ role: "player", token: links["Player 1"] as string }),
      "player-2": await h.live({ role: "player", token: links["Player 2"] as string }),
    };
    const all = Object.values(viewers);
    const take = (): ReplayCells[ReplayState] => ({
      dm: cellsOf(viewers.dm, sceneId),
      "player-1": cellsOf(viewers["player-1"], sceneId),
      "player-2": cellsOf(viewers["player-2"], sceneId),
    });
    const cells = {} as Record<ReplayState, ReplayCells[ReplayState]>;
    cells.ambush = take();

    await ack(viewers.dm, FOG_INTENTS.setAll, { sceneId, fogged: false });
    for (const c of all) await barrier(c);
    cells["ambush-revealed"] = take();

    // End → Start "Escort to the Ford" with the joining PCs' pets (the Start dialog's default).
    await ack(viewers.dm, "cbt.end", { encounterId: ambush.id });
    const escort = db
      .select()
      .from(encounter)
      .where(eq(encounter.name, "Escort to the Ford"))
      .get();
    const pets = db
      .select()
      .from(entity)
      .all()
      .filter((e) => e.companionOf !== null && e.kind === "monster")
      .map((e) => e.id);
    await ack(viewers.dm, "cbt.start", { encounterId: escort?.id, sceneId, petIds: pets });
    for (const c of all) await barrier(c);
    cells.escort = take();

    // Players draw a subset of the DM's tokens: a hidden one only when they own it.
    for (const state of Object.keys(cells) as ReplayState[]) {
      const dmIds = new Set(cells[state].dm.tokens.map((t) => t.id));
      for (const v of ["player-1", "player-2"] as const) {
        const mine = cells[state][v].tokens;
        expect(mine.filter((t) => !dmIds.has(t.id))).toEqual([]);
        expect(mine.filter((t) => t.hidden && !t.owned)).toEqual([]);
      }
    }
    for (const c of [viewers["player-1"], viewers["player-2"]]) {
      expect(leakScan(h.s, c)).toEqual([]);
    }

    const text = render(cells);
    if (process.env.UPDATE_CELLS === "1") writeFileSync(GENERATED, text);
    expect(readFileSync(GENERATED, "utf8").replaceAll("\r\n", "\n")).toBe(text);
  }, 60_000);
});
